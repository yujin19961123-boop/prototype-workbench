import assert from "node:assert/strict";
import { conversations, initialIMState, selectIMConversation, sendIMMessage, setIMFilter, setIMQuery, updateIMDraft, visibleIMConversations } from "../src/project/im-model.ts";

const source = structuredClone(conversations);
const original = initialIMState();
let state = updateIMDraft(original, "project", "项目群待发送内容");
state = selectIMConversation(state, "mei");
state = updateIMDraft(state, "mei", "给美玲的独立草稿");
state = selectIMConversation(state, "project");
assert.equal(state.drafts.project, "项目群待发送内容");
assert.equal(state.drafts.mei, "给美玲的独立草稿");
assert.equal(original.drafts.project, "");
assert.equal(original.drafts.mei, "");
assert.equal(state.history, original.history, "切会话和输入不修改消息");
console.log("PASS starter IM：每会话独立草稿、切换恢复与不可变输入。");

const beforeSend = state;
state = sendIMMessage(state, "14:08");
const sent = state.history.project.at(-1);
assert.equal(sent.text, "项目群待发送内容");
assert.equal(sent.time, "14:08");
assert.equal(sent.id, "project-local-1");
assert.equal(sent.outgoing, true);
assert.equal(state.drafts.project, "");
assert.equal(state.drafts.mei, beforeSend.drafts.mei);
assert.equal(state.history.mei, beforeSend.history.mei);
assert.equal(state.history.review, beforeSend.history.review);
assert.equal(beforeSend.history.project.length + 1, state.history.project.length);
assert.equal(beforeSend.history.project.length, original.history.project.length);
state = updateIMDraft(state, "project", "  第二条消息  ");
state = sendIMMessage(state, "14:09");
assert.equal(state.history.project.at(-1).id, "project-local-2");
assert.equal(state.history.project.at(-1).text, "第二条消息");
assert.equal(state.history.project.at(-1).time, "14:09");
assert.deepEqual(conversations, source, "发送不能改写模拟来源");
console.log("PASS starter IM：当前房间追加、其他房间不变、仅清当前草稿、确定性 ID 与注入时间。");

const blank = updateIMDraft(state, "project", " \n\t ");
assert.equal(sendIMMessage(blank, "14:10"), blank);
assert.equal(selectIMConversation(state, "missing"), state);
assert.equal(updateIMDraft(state, "missing", "wrong"), state);
const unknown = { ...state, selectedId: "missing" };
assert.equal(sendIMMessage(unknown, "14:10"), unknown);
assert.equal(setIMFilter(state, "invalid"), state);
assert.equal(sendIMMessage(initialIMState(), "14:10").history.project.length, original.history.project.length);
console.log("PASS starter IM：空白不发送、未知会话不写入、非法筛选不改变状态。");

assert.equal(visibleIMConversations(setIMFilter(state, "all")).length, conversations.length);
assert(visibleIMConversations(setIMFilter(state, "unread")).every(conversation => conversation.unread));
assert(visibleIMConversations(setIMFilter(state, "mention")).every(conversation => conversation.mention));
assert.equal(visibleIMConversations(setIMQuery(setIMFilter(state, "all"), " CHEN-no-result ")).length, 0);
assert.equal(visibleIMConversations(setIMQuery(setIMFilter(state, "all"), "陈美玲"))[0].id, "mei");
assert(visibleIMConversations(setIMQuery(setIMFilter(state, "all"), "jordan lee")).some(conversation => conversation.id === "jordan"));
assert.equal(visibleIMConversations(setIMQuery(setIMFilter(state, "all"), "第二条消息"))[0].id, "project");
const derived = visibleIMConversations(state);
derived[0].name = "display-only edit";
assert.deepEqual(conversations, source);
assert.deepEqual(initialIMState(), original, "新实例不复用上一次编辑后的数据");
assert.equal(new Set(conversations.map(conversation => `${conversation.initials}:${conversation.color}`)).size, conversations.length);
console.log("PASS starter IM：三类筛选、姓名/摘要搜索、无结果、不同头像、新实例与展示数据隔离。");
